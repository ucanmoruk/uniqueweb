const relatedProductLinks = (service) => {
  const haystack = `${service.name} ${service.description} ${service.methods.join(" ")}`.toLocaleLowerCase("tr");
  const links = [["Tüm test kütüphanesine dön ↗", "/testler/"]];
  if (haystack.includes("retinol") || haystack.includes("hplc") || haystack.includes("stability")) {
    links.push(["Retinol serum ürün akışı ↗", "/urunler/retinol-serum/"]);
  }
  if (haystack.includes("micro") || haystack.includes("preservative") || haystack.includes("water activity")) {
    links.push(["Bebek şampuanı ürün akışı ↗", "/urunler/bebek-sampuani/"]);
  }
  if (haystack.includes("uv") || haystack.includes("spf") || haystack.includes("stability")) {
    links.push(["Güneş kremi ürün akışı ↗", "/urunler/gunes-kremi/"]);
  }
  if (links.length === 1) {
    links.push(["Hizmetleri incele ↗", "/hizmetler/"], ["Mevzuat kütüphanesi ↗", "/mevzuat/"]);
  }
  return links.slice(0, 4);
};

