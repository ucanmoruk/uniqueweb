const escapeHtml = (value = "") =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

const indent = (value, spaces = 8) =>
  value
    .split("\n")
    .map((line) => (line ? `${" ".repeat(spaces)}${line}` : ""))
    .join("\n");

