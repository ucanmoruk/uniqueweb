const writePage = async (urlPath, html) => {
  const outDir = path.join(rootDir, ...urlPath.split("/").filter(Boolean));
  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, "index.html"), html, "utf8");
};

const data = JSON.parse(await readFile(marketsFile, "utf8"));
const markets = [...data.markets].sort((a, b) => a.name.localeCompare(b.name, "tr"));

await writePage("/mevzuat/", renderIndex({ markets, updated: data.updated }));
console.log("- /mevzuat/");

for (const market of markets) {
  await writePage(marketHref(market), renderMarketPage(market, markets));
  console.log(`- ${marketHref(market)}`);
}
