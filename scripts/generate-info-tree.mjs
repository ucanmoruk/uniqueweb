import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const productsDir = path.join(rootDir, "data", "products");

const navItems = [
  ["hakkimizda", "Hakkımızda", "/hakkimizda/"],
  ["hizmetler", "Hizmetler", "/hizmetler/"],
  ["testler", "Testler", "/testler/"],
  ["mevzuat", "Mevzuat", "/mevzuat/"],
  ["raporlar", "Raporlar", "/raporlar/"],
  ["dogrulama", "Doğrulama", "/dogrulama/"],
  ["iletisim", "İletişim", "/iletisim/"]
];

const escapeHtml = (value = "") =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

const indent = (value, spaces = 8) =>
  value
    .split("\n")
    .map((line) => (line ? `${" ".repeat(spaces)}${line}` : ""))
    .join("\n");

const header = (activeNav) => `
<header class="site-header">
  <a class="brand" href="/" aria-label="Unique Analyse ana sayfa"><img src="/assets/unique-analyse-logo.png" alt="Unique Analyse" /></a>
  <nav class="nav" aria-label="Ana menü">
${navItems
  .map(([key, label, href]) => `    <a${key === activeNav ? ' class="active"' : ""} href="${href}">${label}</a>`)
  .join("\n")}
  </nav>
  <a class="header-action" href="/iletisim/">Teklif al ↗</a>
</header>`;

const footer = () => `
<footer class="site-footer">
  <img src="/assets/unique-analyse-logo.png" alt="Unique Analyse" />
  <p>ISO/IEC 17025 akredite analiz laboratuvarı · Kozmetik, deterjan, ilaç ve hammadde sektörleri</p>
  <span>© 2026 Unique Analyse</span>
</footer>`;

const pageShell = ({ title, description, activeNav, main }) => `<!doctype html>
<html lang="tr">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="description" content="${escapeHtml(description)}" />
    <title>${escapeHtml(title)}</title>
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@300;400;500;600;700;800&display=swap" rel="stylesheet" />
    <link rel="stylesheet" href="/styles.css?v=3" />
  </head>
  <body>
    <!-- Generated by scripts/generate-info-tree.mjs. Edit data/products/*.json instead. -->
${indent(header(activeNav), 4)}

    <main>
${indent(main, 6)}
    </main>

${indent(footer(), 4)}
    <script src="/script.js?v=3"></script>
  </body>
</html>`;

const hero = (page, extraClass = "") => `
<section class="page-hero template-hero${extraClass ? ` ${extraClass}` : ""}">
  <p class="eyebrow">${page.eyebrow}</p>
  <h1>${page.h1}</h1>
  <p>${page.lead}</p>
</section>`;

const toc = (title, items = []) => `
<aside class="toc-panel">
  <span>${title}</span>
${items.map(([label, id]) => `  <a href="#${id}">${label}</a>`).join("\n")}
</aside>`;

const paragraphs = (items = []) => items.map((item) => `<p>${item}</p>`).join("\n");

const cards = (items = [], className = "") => {
  if (!items.length) return "";
  return `
<div class="template-grid${className ? ` ${className}` : ""}">
${items
  .map(
    ([label, title, body]) => `  <article><span>${label}</span><h3>${title}</h3><p>${body}</p></article>`
  )
  .join("\n")}
</div>`;
};

const list = (items = [], ordered = false) => {
  if (!items.length) return "";
  const tag = ordered ? "ol" : "ul";
  const className = ordered ? "template-list ordered" : "template-list";
  return `<${tag} class="${className}">
${items.map((item) => `  <li>${item}</li>`).join("\n")}
</${tag}>`;
};

const compliance = (items = []) => {
  if (!items.length) return "";
  return `<div class="compliance-table">
${items.map(([title, body]) => `  <div><b>${title}</b><span>${body}</span></div>`).join("\n")}
</div>`;
};

const timeline = (items = []) => {
  if (!items.length) return "";
  return `<div class="timeline-list">
${items
  .map(
    ([time, title, body]) =>
      `  <article><span>${time}</span><h3>${title}</h3><p>${body}</p></article>`
  )
  .join("\n")}
</div>`;
};

const section = (item) => `
<h2 id="${item.id}">${item.title}</h2>
${[
  paragraphs(item.paragraphs),
  cards(item.cards, item.cardsClass),
  list(item.list),
  list(item.orderedList, true),
  compliance(item.compliance),
  timeline(item.timeline)
]
  .filter(Boolean)
  .join("\n")}`;

const linkRail = (links = []) => {
  if (!links.length) return "";
  return `<div class="link-rail">
${links.map(([label, href]) => `  <a href="${href}">${label}</a>`).join("\n")}
</div>`;
};

const marketLibraryNote = () => `
<div class="template-note market-library-note">
  <b>Diğer ülke gereksinimlerine göz at:</b> Avrupa Birliği, Türkiye, Amerika Birleşik Devletleri, Birleşik Krallık, Suudi Arabistan/SASO-SFDA ve Mısır gibi hedef pazarlar için <a href="/mevzuat/">kozmetik mevzuat kütüphanesini</a> inceleyebilirsiniz.
</div>`;

const cta = (item) => `
<section class="template-cta">
  <p class="eyebrow">${item.eyebrow}</p>
  <h2>${item.title}</h2>
  <p>${item.body}</p>
  <a class="button primary" href="${item.href}">${item.button}</a>
</section>`;

const templateBody = ({ page, activeNav, extraHeroClass, tocTitle, includeMarketLibrary = false }) => {
  const title = tocTitle || page.tocTitle || "Bilgi Ağacı";
  return `
${hero(page, extraHeroClass)}

<section class="section template-shell">
${indent(toc(title, page.toc), 2)}

  <article class="template-content">
    <div class="template-note">
      ${page.note}
    </div>

${indent(page.sections.map(section).join("\n\n"), 4)}

${indent(linkRail(page.links), 4)}

${includeMarketLibrary ? indent(marketLibraryNote(), 4) : ""}

${indent(cta(page.cta), 4)}
  </article>
</section>`;
};

const writeGeneratedPage = async (urlPath, html) => {
  const outDir = path.join(rootDir, ...urlPath.split("/").filter(Boolean));
  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, "index.html"), html, "utf8");
};

const renderProductPage = (product) =>
  pageShell({
    title: product.productPage.metaTitle,
    description: product.productPage.metaDescription,
    activeNav: product.activeNav || "hizmetler",
    main: templateBody({
      page: product.productPage,
      tocTitle: "Bilgi Ağacı",
      includeMarketLibrary: true
    })
  });

const renderTestPage = (product) =>
  pageShell({
    title: product.testPage.metaTitle,
    description: product.testPage.metaDescription,
    activeNav: product.testPage.activeNav || "testler",
    main: templateBody({
      page: product.testPage,
      extraHeroClass: "test-hero"
    })
  });

const renderRegulationPage = (product) =>
  pageShell({
    title: product.regulationPage.metaTitle,
    description: product.regulationPage.metaDescription,
    activeNav: product.regulationPage.activeNav || "mevzuat",
    main: templateBody({
      page: product.regulationPage,
      extraHeroClass: "regulation-hero",
      includeMarketLibrary: true
    })
  });

const renderKnowledgeIndex = (products) =>
  pageShell({
    title: "Bilgi Ağacı | Unique Analyse",
    description:
      "Unique Analyse ürün, test ve mevzuat bilgi ağacı. Kozmetik ürünler için laboratuvar testleri, regülasyon ve analiz rehberleri.",
    activeNav: "hizmetler",
    main: `
${hero(
  {
    eyebrow: "// BİLGİ AĞACI",
    h1: "ÜRÜN, TEST VE MEVZUAT SAYFALARI TEK SİSTEMDE.",
    lead:
      "Her ürün için üçlü bir içerik omurgası oluştururuz: ürün test paketi, laboratuvar test metodu ve hedef pazar mevzuatı. Böylece ziyaretçi hangi sorudan başlarsa başlasın doğru hizmet akışına bağlanır."
  },
  "template-hero"
)}

<section class="section knowledge-tree">
  <div class="section-intro wide">
    <p class="eyebrow">OTOMATİK İÇERİK HARİTASI</p>
    <h2>Yayınlanan ürün ağaçları.</h2>
    <p>Bu liste <code>data/products/*.json</code> dosyalarından otomatik üretilir. Yeni ürün eklendiğinde ürün, test ve mevzuat sayfalarıyla birlikte burada da görünür.</p>
  </div>
  <div class="tree-grid">
${products
  .flatMap((product) => [
    `<a href="${product.productPath}"><span>ÜRÜN</span><b>${product.name} test ve belgelendirme süreçleri</b><em>Ürün şablonu ↗</em></a>`,
    `<a href="${product.testPath}"><span>TEST</span><b>${product.name} aktif madde / kalite kontrol metodu</b><em>Test şablonu ↗</em></a>`,
    `<a href="${product.regulationPath}"><span>MEVZUAT</span><b>${product.name} için ÜTS, CPNP ve PIF gereklilikleri</b><em>Mevzuat şablonu ↗</em></a>`
  ])
  .join("\n")}
  </div>
</section>`
  });

const files = (await readdir(productsDir)).filter((file) => file.endsWith(".json"));
const products = [];

for (const file of files) {
  const product = JSON.parse(await readFile(path.join(productsDir, file), "utf8"));
  products.push(product);

  await writeGeneratedPage(product.productPath, renderProductPage(product));
  await writeGeneratedPage(product.testPath, renderTestPage(product));
  await writeGeneratedPage(product.regulationPath, renderRegulationPage(product));

  console.log(`Generated info tree for ${product.name}`);
  console.log(`- ${product.productPath}`);
  console.log(`- ${product.testPath}`);
  console.log(`- ${product.regulationPath}`);
}

await writeGeneratedPage("/bilgi-agaci/", renderKnowledgeIndex(products));
console.log("- /bilgi-agaci/");
